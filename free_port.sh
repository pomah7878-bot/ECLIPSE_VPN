#!/bin/bash
# free_port.sh <порт> — если порт занят посторонним процессом, освобождает его.
# Используется как ExecStartPre в systemd-юнитах, чтобы сервис никогда не
# падал в бесконечный цикл рестартов из-за "address already in use",
# оставшегося от случайно не закрытого ручного запуска.
#
# Опрашивает порт ПОВТОРНО (а не один раз), потому что при быстром
# рестарте старый процесс иногда ещё не успевает полностью освободить
# сокет к моменту разовой проверки (особенно если процесс был в свопе —
# освобождение ресурсов ядром занимает лишнюю секунду-две), из-за чего
# однократная проверка "порт свободен" оказывалась ложной, и новый
# процесс падал с "address already in use" сразу после старта.

PORT="$1"
if [ -z "$PORT" ]; then
    exit 0
fi

MAX_ATTEMPTS=10

for i in $(seq 1 "$MAX_ATTEMPTS"); do
    PID=$(ss -tlnp 2>/dev/null | grep ":${PORT} " | grep -oP 'pid=\K[0-9]+' | head -1)

    if [ -z "$PID" ]; then
        # Порт свободен — но окно гонки короткое, поэтому даём ядру ещё
        # немного времени перед тем, как ExecStartPre завершится и
        # systemd тут же запустит основной процесс.
        sleep 0.3
        exit 0
    fi

    echo "free_port.sh: порт $PORT занят процессом $PID — освобождаю (попытка $i/$MAX_ATTEMPTS)"
    kill "$PID" 2>/dev/null
    sleep 1
    # Если процесс не завершился по-хорошему за секунду — добиваем
    kill -9 "$PID" 2>/dev/null
done

echo "free_port.sh: порт $PORT всё ещё занят после $MAX_ATTEMPTS попыток — запускаюсь как есть"
exit 0
